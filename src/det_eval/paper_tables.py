"""LaTeX table bodies for the paper, generated from results/ so every number traces to a file.

    python -m det_eval.paper_tables          # writes paper/tables/*.tex (main.tex \\input's them)

A table whose inputs are missing is written as a one-row "pending" body, so the paper always builds.
"""

from __future__ import annotations

import json
from pathlib import Path

from .common import REPO_ROOT, load_json, load_yaml

RES = Path("results")
RUNS = Path("runs")
OUT = Path("paper/tables")

LABEL = {
    "yolo26m_nms": "YOLO26m, NMS",
    "yolo26m_nms_ml": "YOLO26m, NMS multi-label",
    "yolo26m_e2e": "YOLO26m, NMS-free",
    "rtdetr_l": "RT-DETR-l",
    "yoloe26m": "YOLOE-26m",
    "cosmos3_edge": "Cosmos 3 Edge",
    "yolo26m_ft_kitti": "YOLO26m-FT, NMS",
    "yolo26m_ft_kitti_e2e": "YOLO26m-FT, NMS-free",
    "yolo26m_ft_kitti_maskvan": "YOLO26m-FT, Van masked",
}
DATASET = {"coco_val2017": "COCO val", "kitti_val": "KITTI val", "nuimages_val3k": "nuImages val"}


def pct(x, nd=1):
    return "--" if x is None or x != x else f"{100 * x:.{nd}f}"


def num(x, nd=2):
    return "--" if x is None or x != x else f"{x:.{nd}f}"


def ci(c):
    return "" if not c else f" {{\\scriptsize[{100 * c[0]:.1f}, {100 * c[1]:.1f}]}}"


def _write(name: str, rows: list[str], ncols: int) -> Path:
    OUT.mkdir(parents=True, exist_ok=True)
    body = rows or [f"\\multicolumn{{{ncols}}}{{c}}{{\\textit{{pending: inputs not in results/ yet}}}} \\\\"]
    path = OUT / f"{name}.tex"
    path.write_text("% generated by python -m det_eval.paper_tables; do not edit\n" + "\n".join(body) + "\n")
    return path


def _metrics(model, dataset, size, ev):
    p = RES / "metrics" / f"{model}__{dataset}__{size}__{ev}.json"
    return load_json(p) if p.exists() else None


def table_main() -> Path:
    rows = []
    order = [("coco_val2017", 640, m) for m in ("yolo26m_nms", "yolo26m_nms_ml", "yolo26m_e2e", "rtdetr_l")]
    order += [("kitti_val", s, m) for s in (640, 1280) for m in ("yolo26m_nms", "yolo26m_nms_ml", "yolo26m_e2e", "rtdetr_l", "yoloe26m")]
    order += [("kitti_val", 640, m) for m in ("yolo26m_ft_kitti", "yolo26m_ft_kitti_e2e", "yolo26m_ft_kitti_maskvan")]
    last = None
    for ds, size, m in order:
        ev = "closed4" if m.startswith("yolo26m_ft") else "full"
        r = _metrics(m, ds, size, ev)
        if r is None or not r.get("coco"):
            continue
        if last is not None and (ds, size) != last:
            rows.append("\\midrule")
        last = (ds, size)
        c = r["coco"]
        k = (r.get("kitti") or {}).get("AP_R40", {}).get("moderate", {})
        kitti = f"{pct(k.get('car'))} / {pct(k.get('person'))}" if k else "--"
        rows.append(f"{LABEL[m]} & {DATASET[ds]} & {size} & {pct(c['AP'])}{ci(c.get('AP_ci95'))} & {pct(c['AP50'])} & "
                    f"{pct(c['AP75'])} & {pct(c['AP_small'])} & {pct(c['AP_medium'])} & {pct(c['AP_large'])} & "
                    f"{pct(c['AR100'])} & {kitti} \\\\")
    return _write("main", rows, 11)


def table_vlm300() -> Path:
    rows = []
    vsum = RUNS / "vlm" / "cosmos3_edge__kitti_val__300.summary.json"
    fail = load_json(RES / "failures.json")["vlm300"] if (RES / "failures.json").exists() else None
    for m in ("yolo26m_nms", "yolo26m_e2e", "rtdetr_l", "yoloe26m", "yolo26m_ft_kitti", "cosmos3_edge"):
        size = "native" if m == "cosmos3_edge" else 640
        r = _metrics(m, "kitti_val", size, "vlm300")
        if r is None:
            continue
        op5, op7 = r["operating_points"]["iou0.5"], r["operating_points"]["iou0.7"]
        key = "all_dets" if m == "cosmos3_edge" else "conf0.25"
        a5, a7 = op5[key], op7[key]
        fr = (fail or {}).get(m)
        cyc = None
        if fr:                                        # cyclist recall at the deploy threshold (conf 0.25; VLM: all boxes)
            tp_c = fr["tp_by_class"].get("cyclist", 0)
            n_c = tp_c + sum(fr["fn_by_class"].get("cyclist", {}).values())
            cyc = {"recall": tp_c / n_c if n_c else float("nan")}
        if m == "cosmos3_edge" and vsum.exists():
            lat = f"{load_json(vsum)['latency_s']['p50'] * 1000:.0f}"
        else:
            arch = "yolo26m_nms" if m == "yolo26m_ft_kitti" else m      # same architecture and head as the zero-shot model
            lp = RUNS / "latency" / f"{arch}__kitti_val__640__trt.summary.json"
            lat = num(load_json(lp)["e2e_ms"]["p50"], 1) if lp.exists() else "--"
        cyc_ap = (r.get("coco") or {}).get("per_class_AP50", {}).get("cyclist")
        rows.append(f"{LABEL[m]} & {num(a5['precision'])} & {num(a5['recall'])} & {num(a5['f1'])} & {num(a7['f1'])} & "
                    f"{pct(cyc_ap)} & {num(cyc.get('recall')) if cyc else '--'} & {lat} \\\\")
    return _write("vlm300", rows, 8)


def table_latency() -> Path:
    rows = []
    for m in ("yolo26m_nms", "yolo26m_e2e", "rtdetr_l", "yoloe26m"):
        pt = RUNS / "latency" / f"{m}__kitti_val__640.summary.json"
        trt = RUNS / "latency" / f"{m}__kitti_val__640__trt.summary.json"
        if not pt.exists():
            continue
        p = load_json(pt)
        t = load_json(trt) if trt.exists() else None
        rows.append(f"{LABEL[m]} & {num(p['e2e_ms']['p50'], 1)} & {num(p['e2e_ms']['p99'], 1)} & "
                    f"{num(t['e2e_ms']['p50'], 1) if t else '--'} & {num(t['e2e_ms']['p99'], 1) if t else '--'} & "
                    f"{num(t['postprocess_ms']['p50'], 1) if t else '--'} & {num(p.get('peak_mem_mb'), 0)} \\\\")
    return _write("latency", rows, 7)


def table_paired() -> Path:
    spec = [("e2e_vs_nms__coco_val2017__640", "NMS-free $-$ NMS", "COCO, 640"),
            ("e2e_vs_nms__kitti_val__640", "NMS-free $-$ NMS", "KITTI, 640"),
            ("e2e_vs_nms__kitti_val__1280", "NMS-free $-$ NMS", "KITTI, 1280"),
            ("mlnms_vs_nms__kitti_val__640", "NMS multi-label $-$ NMS", "KITTI, 640"),
            ("e2e_vs_mlnms__kitti_val__640", "NMS-free $-$ NMS multi-label", "KITTI, 640"),
            ("rtdetr_vs_e2e__kitti_val__640", "RT-DETR $-$ NMS-free", "KITTI, 640"),
            ("ft_vs_nms__kitti_val__640", "Fine-tuned $-$ zero-shot, NMS", "KITTI, 640"),
            ("nms_1280_vs_640__kitti_val", "1280 $-$ 640 px, NMS", "KITTI"),
            ("e2e_1280_vs_640__kitti_val", "1280 $-$ 640 px, NMS-free", "KITTI")]

    def cell(v):
        star = "$^{*}$" if v["significant"] else ""
        return f"{100 * v['diff']:+.1f}{star} {{\\scriptsize[{100 * v['diff_ci95'][0]:+.1f}, {100 * v['diff_ci95'][1]:+.1f}]}}"

    rows = []
    for name, comp, where in spec:
        p = RES / "paired" / f"{name}.json"
        if not p.exists():
            continue
        g = load_json(p)["groups"]
        small = g.get("h<25")
        rows.append(f"{comp} & {where} & {cell(g['all']['AP'])} & {cell(g['all']['AR'])} & "
                    f"{cell(small['AP']) if small else '--'} \\\\")
    return _write("paired", rows, 5)


def table_failures() -> Path:
    p = RES / "failures.json"
    if not p.exists():
        return _write("failures", [], 12)
    f = load_json(p)["vlm300"]
    rows = []
    for m in ("yolo26m_nms", "yolo26m_e2e", "rtdetr_l", "yoloe26m", "yolo26m_ft_kitti", "cosmos3_edge"):
        if m not in f:
            continue
        r = f[m]
        fn, fp = r["fn_types"], r["fp_types"]
        rows.append(f"{LABEL[m]} & {r['tp']} & " + " & ".join(str(fn[t]) for t in ("loose", "crowded", "confused", "small", "occluded", "missed"))
                    + " & " + " & ".join(str(fp[t]) for t in ("loose", "duplicate", "confused", "unlabeled_small", "background")) + " \\\\")
    return _write("failures", rows, 13)


def table_finetune() -> Path:
    """Per-class AP on KITTI val at 640 px: zero-shot (cyclist by the person-over-bicycle rule) vs. fine-tuned."""
    rows = []
    classes = ("car", "person", "truck", "train")
    spec = [("yolo26m_nms", "full"), ("yolo26m_nms_ml", "full"), ("yolo26m_e2e", "full"), ("rtdetr_l", "full"),
            ("yoloe26m", "full"), None, ("yolo26m_ft_kitti", "closed4"), ("yolo26m_ft_kitti_e2e", "closed4"),
            ("yolo26m_ft_kitti_maskvan", "closed4")]
    for item in spec:
        if item is None:
            rows.append("\\midrule")
            continue
        m, ev = item
        r = _metrics(m, "kitti_val", 640, ev)
        if r is None:
            continue
        c = r["coco"]
        open_model = m.startswith("yolo26m_ft") or m == "yoloe26m"
        src = _metrics(m, "kitti_val", 640, "full" if open_model else "cyclist")
        cyc = (src or {}).get("coco", {}).get("per_class_AP", {}).get("cyclist")
        rows.append(f"{LABEL[m]} & {pct(c['AP'])} & " + " & ".join(pct(c["per_class_AP"].get(k)) for k in classes) +
                    f" & {pct(cyc)}{'' if open_model else chr(36) + '^{r}' + chr(36)} & {pct(c['AR100'])} \\\\")
    if rows and rows[-1] == "\\midrule":
        rows.pop()
    return _write("finetune", rows, 8)


def table_commands() -> Path:
    """One row per distinct command recorded in the run manifests (the exact configuration lives in
    configs/experiments.yaml, which every command reads)."""
    seen, rows = set(), []
    globs = ["runs/preds/*.manifest.json", "runs/latency/*.manifest.json", "runs/vlm/*.manifest.json",
             "runs/ultra_val/*.manifest.json", "runs/finetune/*/train.json.manifest.json"]
    for g in globs:
        for p in sorted(Path(".").glob(g)):
            cmd = load_json(p).get("command", "")
            if not cmd:
                continue
            cmd = cmd.replace("/work/src/det_eval/", "").replace("src/det_eval/", "")
            for mod in ("run", "finetune", "ultra_val", "vlm_grounding", "latency", "predict_ultralytics"):
                cmd = cmd.replace(f"{mod}.py ", f"python -m det_eval.{mod} ")
            cmd = cmd.split("/")[-1] if cmd.startswith("/") and " " not in cmd else cmd
            if "-m det_eval" in cmd:
                cmd = cmd[cmd.index("python -m"):] if "python -m" in cmd else cmd
            if cmd in seen:
                continue
            seen.add(cmd)
            esc = cmd.replace("\\", "/").replace("_", "\\_").replace("&", "\\&")
            rows.append(f"\\texttt{{{esc}}} \\\\")
    return _write("commands", rows, 1)


def table_repro() -> Path:
    rows = []
    for p in sorted((RUNS / "preds").glob("*.manifest.json")):
        mf = load_json(p)
        rt = mf.get("runtime", {})
        name = p.name.replace(".json.manifest.json", "")
        model, ds, size = name.split("__")
        pk = mf.get("predict_kwargs") or {}
        head = "one-to-one" if pk.get("nms") is False else ("NMS, multi-label" if pk.get("multi_label") else
                                                            ("NMS" if mf.get("kind") == "yolo" else "--"))
        rows.append(f"{LABEL.get(model, model)} & {Path(str(mf.get('weights'))).name.replace('_', chr(92) + '_')} & "
                    f"{DATASET.get(ds, ds)} ({mf.get('n_images')}) & {size} & {mf.get('conf')} / {head} & "
                    f"{'FP16' if mf.get('fp16') else 'FP32'} & Orin Nano 8GB & Ultralytics {rt.get('ultralytics', '?')}, torch {rt.get('torch', '?').split('+')[0]} \\\\")
    vm = RUNS / "vlm" / "cosmos3_edge__kitti_val__300.json.manifest.json"
    if vm.exists():
        mf = load_json(vm)
        rt = mf.get("runtime", {})
        rows.append(f"Cosmos 3 Edge & nvidia/Cosmos3-Edge & KITTI subset (300) & native & greedy, no thinking & BF16 & "
                    f"Orin Nano 8GB & transformers 5.21.0.dev0 (main) \\\\")
    return _write("repro", rows, 8)


def main() -> None:
    import os

    os.chdir(REPO_ROOT)
    for fn in (table_main, table_vlm300, table_latency, table_paired, table_failures, table_finetune, table_repro,
               table_commands):
        print(fn())


if __name__ == "__main__":
    main()
